/**
 * Prompt Boost — the two dictionaries behind every visible string.
 *
 * The namespace is `promptBoost`; `apply` registers these through
 * `ctx.locale.register` and binds them once, so no component ever writes a
 * literal sentence. Both dictionaries carry exactly the same keys, which is
 * what makes the English fallback path safe.
 *
 * The Host returns already-translated source labels in the stream. They are
 * only a fallback: the four known source ids are localized here so an English
 * UI never shows 记忆.
 */

